import type { ShgFinanceRecurring } from "@/types/database";

// Suscripciones: the date rules of shg_finance_run_recurring() (054), mirrored
// here for what the page shows ("Próximo cobro", the monthly total).

const pad = (n: number) => String(n).padStart(2, "0");

/** The charge date in a month: day_of_month, or the month's last day when
 * it's shorter (31 → 30/09, 28/02). month is 1–12. */
export function chargeDate(year: number, month: number, day: number): string {
  const lastDay = new Date(Date.UTC(year, month, 0)).getUTCDate();
  return `${year}-${pad(month)}-${pad(Math.min(day, lastDay))}`;
}

type Schedule = Pick<ShgFinanceRecurring, "day_of_month" | "starts_on" | "ends_on" | "is_active">;

/** The next charge still to come (after today — today's has already been
 * generated by the time the page shows it). null when paused or ended. */
export function nextChargeDate(sub: Schedule, today: string): string | null {
  if (!sub.is_active) return null;
  const from = sub.starts_on > today ? sub.starts_on : today;
  let [year, month] = from.split("-").map(Number);
  for (let i = 0; i < 3; i++) {
    const date = chargeDate(year, month, sub.day_of_month);
    if (date >= sub.starts_on && date > today) {
      return sub.ends_on && date > sub.ends_on ? null : date;
    }
    month += 1;
    if (month > 12) { month = 1; year += 1; }
  }
  return null;
}

/** What the active subscriptions add up to per month. */
export function monthlyTotal(subs: Pick<ShgFinanceRecurring, "amount" | "is_active">[]): number {
  const total = subs.reduce((sum, s) => sum + (s.is_active ? Number(s.amount) : 0), 0);
  return Math.round(total * 100) / 100;
}
